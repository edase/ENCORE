#!/usr/bin/env python3
"""Encore's rename of a Hekili Forever tree: Hekili -> Encore, deterministically and idempotently.

Usage: python3 tools/encore/rename.py <tree> [--report]

Why a script: Encore is a fork of zmsl/hekili (Hekili Forever). Upstream fixes are taken by re-running this script
on a fresh upstream checkout (the `upstream-renamed` branch) and merging that into Encore, so the rename must be
repeatable and must never touch credit or licence text.

Rules
- Lua: code and string literals are renamed; comments are never touched (file headers carry the GPL notices and
  the credits to Hekili, Hekili Forever, Taco Dog Forever, Catnip and wowsims). A string literal that names the
  original project or its authors (MARKERS) keeps its text, apart from the URL map. Locales/*.lua files are
  generated by tools/locales.py, so their comments are renamed too.
- XML: everything outside <!-- comments -->.
- TOC: the metadata Encore owns (Title, Notes, Author, X-Website) is rewritten; X-Curse-Project-ID (Hekili
  Forever's CurseForge project) is dropped; every other line is renamed.
- Tooling (sh, py, Makefile, yml, toml, json, txt, ignore files): renamed, except lines carrying a MARKER.
- docs/ and Markdown: never touched; they stay Hekili Forever's documentation (README, DEVELOPMENT and CHANGELOG
  are Encore's own, edited by hand).
- Paths: any path outside docs/ with Hekili in it is renamed the same way.
"""
import os
import re
import subprocess
import sys

MARKERS = re.compile(
    r"original|defzach|maintainers|zmsl|github%?\.com/hekili|retail hekili|hekili \(forever\)|taco ?dog|catnip|curseforge",
    re.IGNORECASE,
)
URL_MAP = [
    ("https://github.com/zmsl/hekili/issues", "https://github.com/edase/encore/issues"),
    ("https://github.com/zmsl/hekili/releases", "https://github.com/edase/encore/releases"),
]
WORDS = [
    ("/hek ", "/enc "),
    ("Hekili Forever", "Encore"),
    ("HekiliForever", "Encore"),
    ("HEKILI", "ENCORE"),
    ("Hekili", "Encore"),
    ("hekili", "encore"),
]
CORE_NOTES = (
    "Encore: a rhythm-game style spell highway for WoW Forever. Chad's personal fork of Hekili Forever by defzach "
    "(github.com/zmsl/hekili), based on the original work by Hekili and its maintainers. Not either "
    "original project: report problems at github.com/edase/encore."
)
PACK_NOTES = (
    "Encore's {cls}: the class kit and its default priorities, loaded by Encore. From Hekili Forever by defzach, "
    "based on the original work by Hekili; priorities translated from wowsims/forever (MIT)."
)


def words(s):
    for a, b in WORDS:
        s = s.replace(a, b)
    return s


def urls(s):
    for a, b in URL_MAP:
        s = s.replace(a, b)
    return s


def rename_text(s):
    """Plain text with no comment structure: URL map, then the words unless a marker guards it."""
    s = urls(s)
    return s if MARKERS.search(s) else words(s)


# ---------------------------------------------------------------------------------------------------------- Lua


LONG_OPEN = re.compile(r"\[(=*)\[")


def lua_segments(text):
    """Splits Lua source into (kind, text) segments, kind in code / string / comment."""
    segs, i, start, n = [], 0, 0, len(text)

    def flush(end):
        if end > start:
            segs.append(("code", text[start:end]))

    while i < n:
        c = text[i]
        if c == "-" and text.startswith("--", i):
            flush(i)
            m = LONG_OPEN.match(text, i + 2)
            if m:
                close = "]" + m.group(1) + "]"
                k = text.find(close, m.end())
                end = n if k < 0 else k + len(close)
            else:
                k = text.find("\n", i)
                end = n if k < 0 else k
            segs.append(("comment", text[i:end]))
            i = start = end
            continue
        if c == "[":
            m = LONG_OPEN.match(text, i)
            if m:
                flush(i)
                close = "]" + m.group(1) + "]"
                k = text.find(close, m.end())
                end = n if k < 0 else k + len(close)
                segs.append(("string", text[i:end]))
                i = start = end
                continue
        if c in "\"'":
            flush(i)
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == c:
                    j += 1
                    break
                if text[j] == "\n":
                    break
                j += 1
            segs.append(("string", text[i:j]))
            i = start = j
            continue
        i += 1
    flush(n)
    return segs


def lua_rename(text, report=None, path=""):
    out = []
    for kind, seg in lua_segments(text):
        new = seg
        if kind == "code":
            new = words(seg)
        elif kind == "string":
            if seg in ('"hek"', "'hek'"):
                new = seg[0] + "enc" + seg[0]
            else:
                new = urls(seg)
                if not MARKERS.search(seg):  # each literal decides for itself: a path beside a credit is still a path
                    new = words(new)
            if report is not None and new != seg and not re.fullmatch(r"[\"']?[\w./\\:-]*[\"']?", seg):
                report.append(f"{path}: {seg[:110]!r} -> {new[:110]!r}")
        out.append(new)
    return "".join(out)


# ---------------------------------------------------------------------------------------------------- other kinds


def xml_rename(text):
    parts = re.split(r"(<!--.*?-->)", text, flags=re.S)
    return "".join(p if p.startswith("<!--") else rename_text_lines(p) for p in parts)


def rename_text_lines(text):
    return "".join(rename_text(line) for line in text.splitlines(keepends=True))


def toc_rename(text, path):
    cls = os.path.basename(path)[len("Hekili_") : -len(".toc")] if os.path.basename(path).startswith("Hekili_") else ""
    out = []
    for line in text.splitlines(keepends=True):
        nl = "\n" if line.endswith("\n") else ""
        key = line.split(":", 1)[0].strip() if line.startswith("##") else ""
        if key == "## X-Curse-Project-ID":
            continue
        if key == "## Notes":
            if cls == "Shared":
                line = "## Notes: Encore's shared content (racials, consumables, items, common auras). From Hekili Forever by defzach, based on the original work by Hekili." + nl
            elif cls:
                line = "## Notes: " + PACK_NOTES.format(cls=cls) + nl
            else:
                line = "## Notes: " + CORE_NOTES + nl
        elif key == "## Author":
            line = "## Author: Chad (edase), from Hekili Forever by defzach" + nl
        elif key == "## X-Website":
            line = "## X-Website: https://github.com/edase/encore" + nl
        else:
            line = words(urls(line))
        out.append(line)
    return "".join(out)


LUA_NAMES = {".luacheckrc", ".busted"}
TOOLING_EXT = {".sh", ".py", ".yml", ".yaml", ".toml", ".json", ".txt", ".ps1", ".cfg", ".simc"}
TOOLING_NAMES = {"Makefile", ".gitignore", ".styluaignore", ".pkgmeta", ".gitattributes", ".editorconfig", ".luarc.json"}
SKIP_NAMES = {"LICENSE", "LICENSE-wowsims.txt", "CREDITS.md"}


def kind_of(rel):
    base = os.path.basename(rel)
    ext = os.path.splitext(base)[1]
    if base in SKIP_NAMES or rel.startswith(("src/Hekili/Libs/", "src/Encore/Libs/", "tools/encore/", "docs/")):
        return None
    if ext == ".lua" or base in LUA_NAMES:
        return "lua"
    if ext == ".toc":
        return "toc"
    if ext == ".xml":
        return "xml"
    if ext == ".md":
        return None
    if ext in TOOLING_EXT or base in TOOLING_NAMES:
        return "text"
    return None


def new_path(rel):
    if rel.startswith(("docs/", "tools/encore/")):
        return rel
    parts = rel.split("/")
    return "/".join(words(p) for p in parts)


def main():
    root = os.path.abspath(sys.argv[1])
    report = [] if "--report" in sys.argv else None
    files = subprocess.run(["git", "-C", root, "ls-files", "-z"], capture_output=True, check=True).stdout
    files = [f for f in files.decode().split("\0") if f]
    changed = 0
    for rel in files:
        kind = kind_of(rel)
        full = os.path.join(root, rel)
        if kind:
            with open(full, encoding="utf-8", newline="") as fh:
                text = fh.read()
            if kind == "lua" and "/Locales/" in rel:
                new = rename_text_lines(text)  # generated by tools/locales.py: its comments are renamed too
            elif kind == "lua":
                new = lua_rename(text, report, rel)
            elif kind == "toc":
                new = toc_rename(text, rel)
            elif kind == "xml":
                new = xml_rename(text)
            else:
                new = rename_text_lines(text)
            if new != text:
                changed += 1
                with open(full, "w", encoding="utf-8", newline="") as fh:
                    fh.write(new)
    moved = 0
    for rel in files:
        dst = new_path(rel)
        if dst != rel and os.path.exists(os.path.join(root, rel)):
            os.makedirs(os.path.dirname(os.path.join(root, dst)), exist_ok=True)
            subprocess.run(["git", "-C", root, "mv", "-k", rel, dst], check=True)
            moved += 1
    print(f"encore_rename: {changed} files rewritten, {moved} paths moved")
    if report is not None:
        print("\n".join(report))


if __name__ == "__main__":
    main()
